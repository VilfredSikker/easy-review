//! Writes the TypeScript for every wire type into one directory, and
//! optionally a barrel that re-exports them.
//!
//! Usage: `protocol-gen <directory> [<barrel>]`. Files a previous run wrote in
//! the directory are removed first, so a type that left the crate leaves no
//! file behind. The barrel imports from `./protocol/generated/`, the
//! directory's place beside desktop-ui's `lib/types.ts`, wherever either is
//! written, so a check that writes both to a temporary place compares the
//! same text.

use std::error::Error;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use er_protocol::{
    Ack, AvailableBranches, Branch, Branches, Command, ErError, ExportOptions, LineCommits, Notice,
    OpenSource, Project, ProjectReviewSettingsPatch, Projects, Resource, ResourceChanged,
    ResourceKey, ResourceVersion, TabKey, Tabs, Versioned,
};
use ts_rs::{Config, TS};

/// The first line ts-rs writes into every file it generates.
const GENERATED_HEADER: &str = "// This file was generated by [ts-rs]";

/// Where the barrel finds the generated files, relative to itself.
const BARREL_IMPORT_DIR: &str = "./protocol/generated";

fn main() -> ExitCode {
    let mut args = std::env::args_os().skip(1).map(PathBuf::from);
    let Some(dir) = args.next() else {
        eprintln!("usage: protocol-gen <directory> [<barrel>]");
        return ExitCode::from(2);
    };
    let barrel = args.next();
    let written = generate(&dir).and_then(|()| match &barrel {
        Some(barrel) => write_barrel(&dir, barrel),
        None => Ok(()),
    });
    match written {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("protocol-gen: {error}");
            ExitCode::FAILURE
        }
    }
}

fn generate(dir: &Path) -> Result<(), Box<dyn Error>> {
    std::fs::create_dir_all(dir)?;
    remove_generated(dir)?;
    // An explicit config, so the caller's TS_RS_* variables cannot change
    // what is written.
    let cfg = Config::new().with_out_dir(dir);
    TabKey::export_all(&cfg)?;
    ResourceVersion::export_all(&cfg)?;
    ResourceKey::export_all(&cfg)?;
    ResourceChanged::export_all(&cfg)?;
    Versioned::<()>::export_all(&cfg)?;
    Tabs::export_all(&cfg)?;
    Project::export_all(&cfg)?;
    Projects::export_all(&cfg)?;
    Branch::export_all(&cfg)?;
    Branches::export_all(&cfg)?;
    AvailableBranches::export_all(&cfg)?;
    ProjectReviewSettingsPatch::export_all(&cfg)?;
    Resource::export_all(&cfg)?;
    Ack::export_all(&cfg)?;
    ErError::export_all(&cfg)?;
    Command::export_all(&cfg)?;
    Notice::export_all(&cfg)?;
    OpenSource::export_all(&cfg)?;
    LineCommits::export_all(&cfg)?;
    ExportOptions::export_all(&cfg)?;
    Ok(())
}

/// Writes `barrel`: one re-export per file ts-rs wrote in `dir`, by name, and
/// nothing else.
fn write_barrel(dir: &Path, barrel: &Path) -> Result<(), Box<dyn Error>> {
    let mut names = Vec::new();
    for entry in std::fs::read_dir(dir)? {
        let path = entry?.path();
        if is_generated(&path)? {
            if let Some(name) = path.file_stem().and_then(|stem| stem.to_str()) {
                names.push(name.to_owned());
            }
        }
    }
    names.sort();
    let mut text = String::from(
        "// This file was generated by `just protocol-gen` from the er-protocol wire types. Do not edit this file manually.\n",
    );
    for name in &names {
        text.push_str(&format!(
            "export type {{ {name} }} from \"{BARREL_IMPORT_DIR}/{name}\";\n"
        ));
    }
    if let Some(parent) = barrel.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(barrel, text)?;
    Ok(())
}

/// Whether ts-rs wrote `path`.
fn is_generated(path: &Path) -> Result<bool, Box<dyn Error>> {
    Ok(path.extension().is_some_and(|ext| ext == "ts")
        && std::fs::read_to_string(path)?.starts_with(GENERATED_HEADER))
}

/// Removes the files in `dir` that ts-rs wrote, and nothing else.
fn remove_generated(dir: &Path) -> Result<(), Box<dyn Error>> {
    for entry in std::fs::read_dir(dir)? {
        let path = entry?.path();
        if is_generated(&path)? {
            std::fs::remove_file(&path)?;
        }
    }
    Ok(())
}
